document.addEventListener("DOMContentLoaded", () => {
    // 1. Main Navigation Active & Hover Droplet Logic
    const mainNavLinks = document.querySelectorAll(".nav:not(.lang-nav) a");
    const currentPath = window.location.pathname;

    mainNavLinks.forEach(link => {
        const linkPath = new URL(link.getAttribute("href"), window.location.href).pathname;
        const isHome =
            (currentPath === "/" || currentPath.endsWith("/index.html")) &&
            linkPath.endsWith("/index.html");
        const isMatch = linkPath === currentPath || isHome;

        link.classList.toggle("active", isMatch);
        if (isMatch) {
            link.classList.add("is-hovered");
        }

        link.addEventListener("mouseenter", () => {
            mainNavLinks.forEach(item => item.classList.remove("is-hovered"));
            link.classList.add("is-hovered");
        });

        link.addEventListener("click", () => {
            mainNavLinks.forEach(item => item.classList.remove("active"));
            link.classList.add("active");
        });
    });

    // 2. Language Switcher (NO / EN) Logic
    const langLinks = document.querySelectorAll(".lang-nav a[data-lang]");
    const urlParams = new URLSearchParams(window.location.search);
    const paramLang = urlParams.get("lang");
    const savedLang = localStorage.getItem("silomax_lang");
    let currentLang = paramLang === "en" || paramLang === "no" ? paramLang : savedLang || "no";

    function applyLanguage(lang) {
        currentLang = lang === "en" ? "en" : "no";
        localStorage.setItem("silomax_lang", currentLang);
        document.documentElement.lang = currentLang;

        const dict = SILOMAX_I18N[currentLang];

        document.querySelectorAll("[data-i18n]").forEach(el => {
            const key = el.getAttribute("data-i18n");
            if (dict && dict[key] !== undefined) {
                el.textContent = dict[key];
            }
        });

        document.querySelectorAll("[data-i18n-html]").forEach(el => {
            const key = el.getAttribute("data-i18n-html");
            if (dict && dict[key] !== undefined) {
                el.innerHTML = dict[key];
            }
        });

        langLinks.forEach(link => {
            const isMatch = link.getAttribute("data-lang") === currentLang;
            link.classList.toggle("active", isMatch);
            if (isMatch) {
                link.classList.add("is-hovered");
            }
        });

        // Recalculate open FAQ accordion heights if on FAQ page
        document.querySelectorAll(".faq-item.active .faq-item-text").forEach(text => {
            text.style.maxHeight = text.scrollHeight + "px";
        });
    }

    langLinks.forEach(link => {
        link.addEventListener("mouseenter", () => {
            langLinks.forEach(item => item.classList.remove("is-hovered"));
            link.classList.add("is-hovered");
        });

        link.addEventListener("click", event => {
            event.preventDefault();
            const selectedLang = link.getAttribute("data-lang");
            applyLanguage(selectedLang);
        });
    });

    applyLanguage(currentLang);

    // 3. Smooth scroll for same-page anchor links
    document.querySelectorAll('a[href*="#"]').forEach(anchor => {
        anchor.addEventListener("click", event => {
            const url = new URL(anchor.getAttribute("href"), window.location.href);
            const samePage =
                url.pathname === window.location.pathname ||
                ((window.location.pathname === "/" || window.location.pathname.endsWith("/index.html")) &&
                    url.pathname.endsWith("/index.html"));

            if (samePage && url.hash) {
                const target = document.querySelector(url.hash);
                if (target) {
                    event.preventDefault();
                    target.scrollIntoView({ behavior: "smooth", block: "start" });
                    history.pushState(null, "", url.hash);
                }
            }
        });
    });
});
